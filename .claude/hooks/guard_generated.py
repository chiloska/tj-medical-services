#!/usr/bin/env python3
"""PreToolUse (Edit|Write): block hand edits to files that src/build.py regenerates."""
import json
import os
import sys

GENERATED_NAMES = {"sitemap.xml", "robots.txt", "llms.txt"}

data = json.load(sys.stdin)
path = (data.get("tool_input") or {}).get("file_path") or ""
root = os.environ.get("CLAUDE_PROJECT_DIR") or data.get("cwd") or os.getcwd()
try:
    rel = os.path.relpath(os.path.abspath(path), os.path.abspath(root)).replace("\\", "/")
except ValueError:  # different drive on Windows
    sys.exit(0)

if (rel.startswith("public/") and (rel.endswith(".html") or os.path.basename(rel) in GENERATED_NAMES)) \
        or rel.endswith(".generated.ts"):
    print(f"{rel} is generated by src/build.py and will be overwritten. "
          "Edit src/data.py or the page function in src/build.py instead "
          "(the rebuild runs automatically after the edit).", file=sys.stderr)
    sys.exit(2)
